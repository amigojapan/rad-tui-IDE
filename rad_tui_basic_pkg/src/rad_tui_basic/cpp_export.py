class CppExportError(ValueError):
    """The project uses behavior that the native exporter cannot preserve."""


def validate_cpp_export(project):
    """Validate the supported native callback subset and project styling."""
    if not (is_phone_shell(project) or is_dt(project) or is_calculator(project) or
            is_tic_tac_toe(project) or is_minesweeper(project)):
        try:
            compile_callbacks(project)
        except CallbackTranslationError as exc:
            raise CppExportError(str(exc)) from exc
    if project.get('hidden', False):
        raise CppExportError('Hidden forms cannot be exported by the native C++ runtime.')
    for control in project.get('controls', []):
        if control.get('syntax_hl', False):
            name = control.get('name_id', '<unnamed>')
            raise CppExportError(f"Control {name!r} uses Python syntax highlighting, which native export does not support.")


def _cpp_string(value):
    """Use byte escapes so C++ source compiles independent of source encoding."""
    return '"' + ''.join('\\x%02x' % byte for byte in str(value).encode('utf-8')) + '"'


def _integer(value, default=0):
    try:
        return int(value)
    except (TypeError, ValueError, OverflowError):
        return default


def _control_initializer(control):
    fields = [
        _integer(control.get('x')), _integer(control.get('y')),
        max(1, _integer(control.get('w'), 1)), max(1, _integer(control.get('h'), 1)),
        _integer(control.get('tool_type')), _cpp_string(control.get('caption', '')),
        _integer(control.get('value')), _integer(control.get('interval'), 1000),
        _integer(control.get('min_val')),
        _integer(control.get('max_val'), 100), _integer(control.get('list_index')),
        _integer(control.get('scroll_offset')), _integer(control.get('scroll_x')),
        _integer(control.get('scroll_y')), _integer(control.get('bg_color'), 12),
        _integer(control.get('fg_color'), -1), _integer(control.get('custom_bg'), -1),
        'true' if control.get('editable', True) else 'false',
        'true' if control.get('h_scroll', False) else 'false',
        'true' if control.get('v_scroll', False) else 'false',
        '{' + ', '.join(_cpp_string(item) for item in control.get('items', [])) + '}',
    ]
    return '    {' + ', '.join(map(str, fields)) + '}'


def _menu_initializer(menu):
    children = ', '.join(_menu_initializer(child) for child in menu.get('sub', []))
    return '{' + _cpp_string(menu.get('label', '')) + ', ' + _cpp_string(menu.get('name', '')) + ', {' + children + '}}'


