def generate_cpp(project):
    """Return a Python-free C++17 source file for supported RAD-TUI projects."""
    validate_cpp_export(project)
    if is_phone_shell(project):
        callbacks = phone_cpp(project)
    elif is_dt(project):
        callbacks = dt_cpp(project)
    elif is_calculator(project):
        callbacks = calculator_cpp(project)
    elif is_tic_tac_toe(project):
        callbacks = tic_tac_toe_cpp(project)
    elif is_minesweeper(project):
        callbacks = minesweeper_cpp(project)
    else:
        callbacks = CALLBACK_SUPPORT + '\n' + compile_callbacks(project)
    controls = ',\n'.join(_control_initializer(item) for item in project.get('controls', []))
    menus = ', '.join(_menu_initializer(item) for item in project.get('menus', []))
    replacements = {
        '@@FORM_X@@': str(_integer(project.get('x'))),
        '@@FORM_Y@@': str(_integer(project.get('y'))),
        '@@FORM_W@@': str(max(2, _integer(project.get('w'), 40))),
        '@@FORM_H@@': str(max(2, _integer(project.get('h'), 20))),
        '@@FORM_TITLE@@': _cpp_string(project.get('title', 'Form')),
        '@@FORM_FG@@': str(_integer(project.get('fg_color'), -1)),
        '@@FORM_BG@@': str(_integer(project.get('custom_bg'), -1)),
        '@@FORM_DISPLAY_BORDER_AND_CAPTION@@': 'true' if project.get('display_border_and_caption', True) else 'false',
        '@@CONTROLS@@': controls,
        '@@CONTROL_NAMES@@': ', '.join(_cpp_string(item.get('name_id', '')) for item in project.get('controls', [])),
        '@@MENUS@@': menus,
        '@@CALLBACK_CODE@@': callbacks,
    }
    output = RUNTIME
    for key, value in replacements.items():
        output = output.replace(key, value)
    return output


def export_cpp(project, filename):
    """Write a C++ source file only after validation and generation succeed."""
    source = generate_cpp(project)
    destination = Path(filename)
    if destination.suffix.lower() != '.cpp':
        destination = destination.with_suffix('.cpp')
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=destination.parent,
                                         prefix='.' + destination.name + '.', suffix='.tmp',
                                         delete=False) as output:
            temporary = Path(output.name)
            output.write(source)
        os.chmod(temporary, destination.stat().st_mode & 0o777 if destination.exists() else 0o644)
        os.replace(temporary, destination)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()
    return destination
